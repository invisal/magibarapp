/** For an `Icon.*` name this table doesn't know. */
export const FALLBACK_GLYPH = "•";

/** Raycast `Icon` names are bare PascalCase identifiers — never a path,
 *  URL, file name, or emoji. */
export function isRaycastIconName(value: string): boolean {
  return /^[A-Z][A-Za-z0-9]*$/.test(value);
}

export function iconGlyph(name: string): string {
  return GLYPHS[name] ?? FALLBACK_GLYPH;
}
